"""
Pydantic schemas for AI queries and chat interactions with Rafael.
"""
from typing import Optional
from pydantic import BaseModel, Field
from API.schemas.message import MessageResponse


class AskRequest(BaseModel):
    """Payload to ask a question to Rafael within a conversation."""
    message: str = Field(..., min_length=1, description="Question or prompt for Rafael")


class AskResponse(BaseModel):
    """Response returned when Rafael answers a question."""
    conversation_id: str = Field(..., description="ID of the conversation in Supabase")
    response: str = Field(..., description="Text response generated by Rafael")
    user_message: MessageResponse = Field(..., description="The user message recorded in Supabase")
    assistant_message: MessageResponse = Field(..., description="Rafael's response recorded in Supabase")


class ChatRequest(BaseModel):
    """Payload for direct chat with Rafael. Creates a conversation automatically if omitted."""
    message: str = Field(..., min_length=1, description="Question or prompt for Rafael")
    conversation_id: Optional[str] = Field(None, description="Optional conversation UUID. If omitted, a new conversation is created automatically.")
    title: Optional[str] = Field(None, description="Optional title if a new conversation is created")
